import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import vm from 'node:vm';

const root=resolve(new URL('./',import.meta.url).pathname);
const generator=join(root,'scripts/render-weekly.mjs');
const template=join(root,'weekly.template.html');

test('renderer embeds supplied evidence safely in a standalone page',async()=>{
  const dir=await mkdtemp(join(tmpdir(),'cfj-weekly-'));
  try{
    const data={version:'test-fixture',window:'test window',summary:{plannedWeeks:53,plannedCaptures:159,captured:1,strictMatchedWeeks:1,countsByOutlet:{}},weeks:[{date:'2025-10-16',matched:true,pairwiseMinutes:90,observations:[{outletId:'bbc',status:'captured',reviewed:true,actualAt:'2025-10-16T12:00:00Z',stories:[{headline:'<script>quoted</script>',section:'main',codes:['reform-conduct']}]}]}]};
    const input=join(dir,'evidence.json'),output=join(dir,'weekly.html');
    await writeFile(input,JSON.stringify(data));
    const run=spawnSync(process.execPath,[generator,input,output],{encoding:'utf8'});
    assert.equal(run.status,0,run.stderr);
    const html=await readFile(output,'utf8');
    assert.match(html,/const EVIDENCE =/);
    assert.ok(html.includes(String.raw`\u003cscript>quoted\u003c/script>`));
    assert.doesNotMatch(html,/fetch\s*\(|XMLHttpRequest|<script>quoted/);
    assert.match(html,/Save HTML/);
    assert.match(html,/Share file/);
    assert.match(html,/Download data/);
    assert.match(html,/prefers-reduced-motion/);
  }finally{await rm(dir,{recursive:true,force:true})}
});

test('eligibility uses reviewed metric booleans and recomputes target tolerance and pairwise span',async()=>{
  const html=await readFile(template,'utf8');
  const first=html.indexOf('const outlets=');
  const eligibleEnd=html.indexOf(';\nfunction statusFor',first);
  const tallyStart=html.indexOf('const categories=',eligibleEnd);
  const tallyEnd=html.indexOf('\nfunction renderCounts',tallyStart);
  assert.ok(first>=0&&eligibleEnd>first&&tallyStart>eligibleEnd&&tallyEnd>tallyStart);
  const code=`const EVIDENCE=globalThis.fixture;\n${html.slice(first,eligibleEnd)}\n${html.slice(tallyStart,tallyEnd)}\n({weekEligible,tally,eligibleWeeks})`;
  const required=['immigrationTopic','migrationCrime','migrationEnforcement','migrantHarm','reformConduct','reformAdverse','reformRoutine'];
  const metrics=Object.fromEntries(required.map(k=>[k,false]));
  const makeWeek=(date,overrides={})=>({date,targetAt:`${date}T12:00:00Z`,matched:true,observations:['bbc','itv','channel4'].map(outletId=>({outletId,status:'captured',reviewed:true,actualAt:`${date}T12:00:00Z`,metrics:{...metrics},stories:[],...overrides[outletId]}))});
  const firstWeek=makeWeek('2025-10-16');
  const secondWeek=makeWeek('2025-10-23',{bbc:{metrics:{...metrics,immigrationTopic:true,reformRoutine:true},stories:Array.from({length:4},()=>({section:'main',codes:['uk-migration']}))}});
  const contextWeek=makeWeek('2025-10-30',{itv:{status:'context-only'}});
  const funcs=vm.runInNewContext(code,{fixture:{weeks:[firstWeek,secondWeek,contextWeek]}});
  const {weekEligible,tally,eligibleWeeks}=funcs;
  assert.equal(eligibleWeeks.length,2,'initial eligible-week list is explicitly strict');
  assert.deepEqual(Array.from(eligibleWeeks,w=>w.date),[firstWeek.date,secondWeek.date]);
  assert.equal(eligibleWeeks.includes(contextWeek),false,'context-only observation cannot enter initial strict denominator');
  assert.equal(weekEligible(contextWeek,'same-day'),true);
  assert.equal(weekEligible(firstWeek),true);
  assert.equal(weekEligible({...firstWeek,matched:false,pairwiseMinutes:999},'strict'),true,'eligibility is recomputed from timestamps, not summary match fields');
  assert.equal(weekEligible({...firstWeek,observations:firstWeek.observations.map(o=>o.outletId==='itv'?{...o,reviewed:false}:o)}),false);
  assert.equal(weekEligible({...firstWeek,observations:firstWeek.observations.map(o=>o.outletId==='bbc'?{...o,metrics:{immigrationTopic:false}}:o)}),false);
  assert.equal(weekEligible({...firstWeek,observations:firstWeek.observations.map(o=>o.outletId==='bbc'?{...o,actualAt:'2025-10-16T14:00:01Z'}:o)}),false);
  assert.equal(weekEligible({...firstWeek,observations:firstWeek.observations.map(o=>o.outletId==='itv'?{...o,actualAt:'2025-10-16T14:01:00Z'}:o)}),false);
  const sixHourSpread={...firstWeek,observations:firstWeek.observations.map((o,i)=>({...o,status:i===1?'context-only':o.status,actualAt:['2025-10-16T06:00:00Z','2025-10-16T12:00:00Z','2025-10-16T18:00:00Z'][i]}))};
  assert.equal(weekEligible(sixHourSpread,'strict'),false);
  assert.equal(weekEligible(sixHourSpread,'same-day'),true,'same-day sensitivity accepts a 12-hour spread and reviewed context-only records');
  const priorLondonDay={...firstWeek,observations:firstWeek.observations.map((o,i)=>i===0?{...o,actualAt:'2025-10-16T23:00:00Z'}:o)};
  assert.equal(weekEligible(priorLondonDay,'same-day'),false,'same UTC date is insufficient when London date differs');
  const overTwelveHours={...firstWeek,observations:firstWeek.observations.map((o,i)=>i===0?{...o,actualAt:'2025-10-16T05:59:00Z'}:i===2?{...o,actualAt:'2025-10-16T18:00:01Z'}:o)};
  assert.equal(weekEligible(overTwelveHours,'same-day'),false);
  const counts=tally();
  assert.equal(counts.bbc.denominator,2);
  assert.equal(counts.itv.denominator,2);
  assert.equal(counts.channel4.denominator,2);
  assert.equal(counts.bbc.immigrationTopic,1,'four example cards on one date count as one qualifying date');
  assert.equal(counts.bbc.migrationEnforcement,0);
  assert.equal(counts.bbc.reformRoutine,1);
  assert.equal(counts.itv.immigrationTopic,0,'reviewed false flags count as absence within the reviewed pool');
  assert.equal(counts.channel4.immigrationTopic,0);
  assert.match(html,/dates out of .*matched weeks/);
  assert.match(html,/Same-day check/);
  assert.match(html,/broader, less comparable view can include headline changes/);
  assert.match(html,/aria-pressed/);
  assert.match(html,/role=\"progressbar\"/);
  assert.match(html,/aria-valuemax=/);
  assert.match(html,/aria-valuenow=/);
  assert.match(html,/id==='channel4'\?'C4':id\.toUpperCase\(\)/);
  assert.match(html,/bbc:'#8fb7ff',itv:'#f1b74b',channel4:'#d4f56b'/);
  assert.match(html,/No relevant coded examples in this reviewed main area; other areas and times remain unknown/);
  assert.match(html,/headline and visible deck or summary text/);
  assert.match(html,/Migration restrictions or enforcement/);
  assert.match(html,/Routine Reform politics/);
  assert.match(html,/all seven metrics were reviewed/);
  assert.match(html,/Removals, interception, deportation and cost rules alone count as migration enforcement, not crime/);
});
