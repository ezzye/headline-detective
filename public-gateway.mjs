import { timingSafeEqual, randomBytes, randomUUID, createHash } from 'node:crypto';
import { Readable } from 'node:stream';
import { createGameServer } from './server.mjs';
import { createDonorPool, DONOR_CONSENT_VERSION } from './donor-pool.mjs';

export const PUBLIC_MODELS=Object.freeze({deepseek:'deepseek-flash',elevenlabs:'eleven_v3'});
const API_PATHS=new Set(['/api/health','/api/session','/api/respond','/api/reveal','/api/story','/api/speak','/api/campaign/session','/api/campaign/respond','/api/campaign/briefing','/api/campaign/reveal']);
const DONOR_PATHS=new Set(['/api/donations/options','/api/donations/status','/api/donations','/api/donations/revoke','/api/donations/mine']);
export const AUDIO_CACHE_LIMITS=Object.freeze({ttlMs:20*60000,maxItemBytes:1024*1024,maxStoredBytes:8*1024*1024});
const error=code=>Object.assign(new Error(code),{code});
const finite=n=>Number.isSafeInteger(n)&&n>=0&&n<=1000000000;
const response=(status,body)=>({status,headers:{'content-type':'application/json; charset=utf-8','cache-control':'no-store','x-content-type-options':'nosniff'},body:JSON.stringify(body),isBase64Encoded:false});
function equal(a,b) { if(typeof a!=='string'||typeof b!=='string')return false;const aa=Buffer.from(a),bb=Buffer.from(b);return aa.length===bb.length&&timingSafeEqual(aa,bb); }
function strict(v,allowed) {if(!v||typeof v!=='object'||Array.isArray(v)||Object.keys(v).some(k=>!allowed.includes(k)))throw error('invalid_schema');}
export function exportSessions(sessions) {return [...sessions].map(([id,s])=>[id,{...s,replies:[...(s.replies || [])],briefingReplies:[...(s.briefingReplies || [])],controllers:undefined,inFlight:0,voiceInFlight:0}]);}
export function restoreSessions(sessions,rows,now=Date.now()) {
  for(const [id,s] of rows || []) if(typeof id==='string'&&s&&Number.isSafeInteger(s.createdAt)&&now-s.createdAt<20*60000&&s.createdAt<=now) sessions.set(id,{...s,replies:new Map(s.replies || []),briefingReplies:new Map(s.briefingReplies || []),controllers:new Set(),inFlight:0,voiceInFlight:0});
}

/** This gateway is called only by an authenticated edge bridge. It is never an
 * open reverse proxy. Provider calls are generated by createGameServer only. */
export function createPublicGateway({config,storagePath,masterKey,state={},persist,fetchImpl=globalThis.fetch,clock=Date.now}={}) {
  if(!config||config.singleConcurrency!==true||config.publicOrigin!=='https://codingforjustice.org.uk'||typeof config.gatewayToken!=='string'||config.gatewayToken.length<32||typeof persist!=='function')throw error('invalid_gateway_configuration');
  const env=config.env || {}, models={...PUBLIC_MODELS,...config.models};
  if(models.deepseek!==PUBLIC_MODELS.deepseek||models.elevenlabs!==PUBLIC_MODELS.elevenlabs)throw error('invalid_model');
  const pool=createDonorPool({enabled:true,storagePath,masterKey,...(config.donorCaps?{caps:config.donorCaps}:{})});
  const ledger={rates:state.rates || {},owner:state.owner || {},sessions:state.sessions || [],requests:state.requests || {},audioCache:state.audioCache || {},audioCacheBytes:0};
  for(const provider of Object.keys(PUBLIC_MODELS)) {
    const report=config.ownerReports?.[provider] || config.owner?.[provider];
    if(!ledger.owner[provider]) ledger.owner[provider]={remainingUnits:finite(report?.remainingUnits)?report.remainingUnits:0,manual:report?.allowManual===true,mode:provider==='deepseek'?'provider_prepaid':'provider_characters',manualFunded:report?.manualFunded===true,asOf:report?.asOf || null,usedUnits:0,reservedCalls:0,balanceInitialized:finite(report?.remainingUnits),status:'active',checkedAt:0,checkedAvailable:false};
  }
  let visitor=null,busy=false;
  const save=async()=>{pruneAudio();await pool.flush();ledger.sessions=exportSessions(app.sessions);await persist(ledger);};
  function pruneAudio() {
    const now=clock();let total=0;
    for(const [id,entry] of Object.entries(ledger.audioCache)) {
      const body=entry?.result?.body;
      const valid=entry && typeof body==='string' && /^[A-Za-z0-9+/]+={0,2}$/.test(body) && Number.isSafeInteger(entry.createdAt) && entry.createdAt<=now && now-entry.createdAt<AUDIO_CACHE_LIMITS.ttlMs && Number.isSafeInteger(entry.dataBytes) && entry.dataBytes>0 && entry.dataBytes<=AUDIO_CACHE_LIMITS.maxItemBytes && body.length<=Math.ceil(AUDIO_CACHE_LIMITS.maxItemBytes/3)*4;
      if(!valid || Buffer.from(body,'base64').length!==entry.dataBytes || Buffer.from(body,'base64').toString('base64')!==body) {delete ledger.audioCache[id];continue;}
      // Rebuild headers from validated bytes; snapshot data cannot supply cookies,
      // redirects, content types or other unsafe response headers.
      entry.result={status:200,headers:{'content-type':'audio/mpeg','content-length':String(entry.dataBytes),'cache-control':'no-store','x-content-type-options':'nosniff'},body,isBase64Encoded:true};
      total+=Buffer.byteLength(JSON.stringify(entry));
    }
    const byAge=Object.entries(ledger.audioCache).sort((a,b)=>(a[1].lastUsedAt || a[1].createdAt)-(b[1].lastUsedAt || b[1].createdAt));
    for(const [id,entry] of byAge) {if(total<=AUDIO_CACHE_LIMITS.maxStoredBytes)break;total-=Buffer.byteLength(JSON.stringify(entry));delete ledger.audioCache[id];}
    ledger.audioCacheBytes=total;
  }
  function voiceAction(input) {
    if(input.performance!==undefined&&!['calm','theatrical'].includes(input.performance))return null;
    const session=app.sessions.get(input.sessionId),saved=session?.replies.get(input.replyId);
    if(!session || session.ownerVisitor!==visitor || input.kind!=='reply' || !saved || saved.outletId!==input.outletId)return null;
    const deskIndex=session.desks.findIndex(d=>d.outletId===input.outletId),voiceId=env['ELEVENLABS_VOICE_'+String.fromCharCode(65+deskIndex)];
    return createHash('sha256').update(JSON.stringify([visitor,input.sessionId,input.outletId,input.kind,input.replyId,input.performance || 'calm',models.elevenlabs,voiceId,saved.text])).digest('hex');
  }
  function storeAudio(id,result) {
    const dataBytes=Buffer.from(result.body,'base64').length;
    if(result.status!==200||dataBytes<1||dataBytes>AUDIO_CACHE_LIMITS.maxItemBytes)return;
    ledger.audioCache[id]={createdAt:clock(),lastUsedAt:clock(),dataBytes,result:{body:result.body}};pruneAudio();
  }
  pruneAudio();
  function rate() {
    const day=new Date(clock()).toISOString().slice(0,10),key=visitor+':'+day;
    for(const name of Object.keys(ledger.rates)) if(!name.endsWith(':'+day))delete ledger.rates[name];
    return ledger.rates[key] ||= {requests:0,donations:0,paidCalls:0,deepseek:0,elevenlabs:0};
  }
  function debitRate(provider,units) {const r=rate(),limit=provider==='deepseek'?262144:12000;if(r.paidCalls>=24||r[provider]+units>limit)throw error('visitor_budget_exhausted');r.paidCalls++;r[provider]+=units;}
  const credentials={deepseek:env.DEEPSEEK_API_KEY,elevenlabs:env.ELEVENLABS_API_KEY || env.ELEVEN_LABS_API_KEY || env.XI_API_KEY};
  async function ownerAvailable(provider,units) {
    const owner=ledger.owner[provider],key=credentials[provider];if(!key||owner.status!=='active')return false;
    if(clock()-owner.checkedAt>60000||!owner.checkedAt) {
      let known=false,available=false,remaining=null;
      try {
        const endpoint=provider==='deepseek'?'https://api.deepseek.com/user/balance':'https://api.elevenlabs.io/v1/user/subscription';
        const result=await fetchImpl(endpoint,{method:'GET',redirect:'error',signal:AbortSignal.timeout(8000),headers:provider==='deepseek'?{authorization:'Bearer '+key}:{'xi-api-key':key}});
        if(result.ok) {const data=await result.json();if(provider==='deepseek'&&typeof data.is_available==='boolean'){known=true;available=data.is_available;}
          if(provider==='elevenlabs'&&finite(data.character_limit)&&finite(data.character_count)){known=true;remaining=Math.max(0,data.character_limit-data.character_count);available=remaining>=units;}}
        else if([401,402,403].includes(result.status)){known=true;available=false;owner.status='unavailable';}
      } catch {}
      owner.checkedAt=clock();const manualCurrent=owner.manualFunded&&Number.isFinite(Date.parse(owner.asOf))&&clock()-Date.parse(owner.asOf)>=0&&clock()-Date.parse(owner.asOf)<=86400000;
      owner.checkedAvailable=known?available:provider==='deepseek'?manualCurrent:owner.manual;
      if(known&&!available)owner.status='unavailable';
      if(remaining!==null) {owner.remainingUnits=owner.balanceInitialized?Math.min(owner.remainingUnits,remaining):remaining;owner.balanceInitialized=true;}
      // DeepSeek provider_prepaid mode uses the freshly verified finite provider
      // balance and provider-side insufficient-credit stop. Never invent a token
      // entitlement or money-to-token conversion, and never trigger a top-up.
      await save();
    }
    return owner.status==='active'&&owner.checkedAvailable&&(provider==='deepseek'||owner.remainingUnits>=units);
  }
  async function donorAllowance(provider,key,units) {
    const endpoint=provider==='deepseek'?'https://api.deepseek.com/user/balance':'https://api.elevenlabs.io/v1/user/subscription';
    let result,data;
    try {result=await fetchImpl(endpoint,{method:'GET',redirect:'error',signal:AbortSignal.timeout(8000),headers:provider==='deepseek'?{authorization:'Bearer '+key}:{'xi-api-key':key}});}
    catch {throw error('provider_unavailable');} // Unknown/free-read failure: no paid call or key swap.
    if(!result.ok) {
      if([401,402,403].includes(result.status))throw Object.assign(error('provider_unavailable'),{status:result.status});
      throw error('provider_unavailable');
    }
    try {data=await result.json();}catch {throw error('provider_unavailable');}
    if(provider==='deepseek') {
      if(data?.is_available===true)return;
      if(data?.is_available===false)throw Object.assign(error('provider_unavailable'),{status:402});
      throw error('provider_unavailable');
    }
    // Fixed approved eleven_v3 model uses the verified 1-character multiplier.
    // Ignore account overage/extension flags: require known prepaid characters.
    if(!finite(data?.character_limit)||!finite(data?.character_count))throw error('provider_unavailable');
    if(Math.max(0,data.character_limit-data.character_count)<units)throw Object.assign(error('provider_unavailable'),{status:402});
  }
  async function providerFetch(url,options) {
    const body=JSON.parse(options.body),provider=url==='https://api.deepseek.com/chat/completions'?'deepseek':url.startsWith('https://api.elevenlabs.io/v1/text-to-speech/')?'elevenlabs':null;
    if(!provider||options.method!=='POST')throw error('provider_route_rejected');
    if(provider==='deepseek'&&body.model!==models.deepseek)throw error('invalid_model');
    if(provider==='elevenlabs') {
      const parsed=new URL(url),voice=decodeURIComponent(parsed.pathname.split('/').at(-1));
      if(parsed.origin!=='https://api.elevenlabs.io'||![env.ELEVENLABS_VOICE_A,env.ELEVENLABS_VOICE_B,env.ELEVENLABS_VOICE_C,env.ELEVENLABS_VOICE_D].includes(voice)||body.model_id!==models.elevenlabs)throw error('invalid_model');
    }
    const units=provider==='deepseek'?Buffer.byteLength(options.body,'utf8')+body.max_tokens:body.text?.length;
    if(!finite(units)||units<1||units>(provider==='deepseek'?65536:6000))throw error('request_budget_invalid');
    const dispatch=async key=>{
      const headers=provider==='deepseek'?{authorization:'Bearer '+key,'content-type':'application/json'}:{'xi-api-key':key,'content-type':'application/json'};
      const result=await fetchImpl(url,{...options,headers,redirect:'error'});
      if(!result.ok)throw Object.assign(error('provider_unavailable'),{status:result.status});
      if(provider==='deepseek') {const payload=await result.json(),actual=payload?.usage?.total_tokens;return {value:{ok:true,status:200,json:async()=>payload},actualUnits:finite(actual)&&actual<=units?actual:undefined};}
      return {value:result,actualUnits:units};
    };
    if(await ownerAvailable(provider,units)) {
      const owner=ledger.owner[provider];debitRate(provider,units);if(provider==='elevenlabs')owner.remainingUnits-=units;owner.usedUnits=(owner.usedUnits || 0)+units;owner.reservedCalls=(owner.reservedCalls || 0)+1;
      try {await save();}catch {throw error('durability_unavailable');} // No paid fetch before this save.
      let result;
      try {result=await dispatch(credentials[provider]);}
      catch(e) {
        if([401,402,403,429].includes(e.status)){owner.status='unavailable';await save();}
        else {await save();throw error('provider_unavailable');} // Uncertain owner call: never swap/retry.
      }
      if(result) {if(finite(result.actualUnits)&&result.actualUnits<=units){owner.usedUnits-=units-result.actualUnits;if(provider==='elevenlabs')owner.remainingUnits+=units-result.actualUnits;};await save();return result.value;}
    }
    return pool.withProvider({provider,maxUnits:units,nonce:randomUUID()},async({key})=>{try{await donorAllowance(provider,key,units);return await dispatch(key);}catch(e){if(e.status===402)e.status=401;throw e;}},{
      onReserved:async()=>{debitRate(provider,units);await save();},onSettled:async()=>save()
    });
  }
  const app=createGameServer({env:{...env,CFJ_PUBLIC_RUNTIME:'true',DEEPSEEK_API_KEY:'private-gateway',DEEPSEEK_MODEL:models.deepseek,ELEVENLABS_API_KEY:'private-gateway',ELEVENLABS_MODEL:models.elevenlabs},fetchImpl:providerFetch,clock});
  restoreSessions(app.sessions,ledger.sessions,clock());
  async function gameRequest(method,url,body) {return new Promise(resolve=>{
    const req=Readable.from([Buffer.from(body)]);req.method=method;req.url=url;req.headers={host:'127.0.0.1','content-type':'application/json',origin:'http://127.0.0.1'};
    let status,headers;const res={writeHead(s,h){status=s;headers=h;},end(bytes){const raw=Buffer.from(bytes || '');const audio=String(headers?.['content-type'] || '').startsWith('audio/');resolve({status,headers,body:audio?raw.toString('base64'):raw.toString(),isBase64Encoded:audio});}};app.server.emit('request',req,res);
  });}
  async function handle({method,path,headers={},body=''}={}) {
    const h=Object.fromEntries(Object.entries(headers).map(([k,v])=>[k.toLowerCase(),v]));
    if(!equal(h['x-gateway-token'],config.gatewayToken))return response(403,{error:'bridge_required'});
    if(h.origin!==config.publicOrigin)return response(403,{error:'origin_rejected'});
    if(!/^[a-f0-9]{32,64}$/.test(h['x-visitor-hash'] || ''))return response(403,{error:'visitor_required'});
    if(!['GET','POST'].includes(method)||!API_PATHS.has(path)&&!DONOR_PATHS.has(path))return response(404,{error:'not_found'});
    if(typeof body!=='string'||Buffer.byteLength(body)>16384)return response(413,{error:'body_too_large'});
    if(method==='POST'&&!/^application\/json(?:;|$)/i.test(h['content-type'] || ''))return response(415,{error:'application_json_required'});
    if(busy)return response(503,{error:'serialized_gateway_busy'});
    busy=true;visitor=h['x-visitor-hash'];
    try {
      const r=rate();if(r.requests>=200)return response(429,{error:'visitor_rate_limit'});r.requests++;
      if(method==='GET') {
        if(path==='/api/health'){await save();return response(200,{ok:true,enabled:true,models:{...models},donationsEnabled:pool.enabled});}
        if(path==='/api/donations/options'){await save();return response(200,{enabled:pool.enabled,models:{...models},providers:Object.entries(models).map(([provider,model])=>({provider,model,unit:provider==='deepseek'?'tokens':'characters'})),modes:['prepaid_remaining'],consentVersion:DONOR_CONSENT_VERSION,withdrawal:'Stops new calls; already dispatched calls may finish. Donations do not buy editorial control.'});}
        if(path==='/api/donations/status'){await save();return response(200,pool.status());}
        return response(405,{error:'method_not_allowed'});
      }
      let input;try {input=JSON.parse(body);}catch{return response(400,{error:'invalid_json'});}
      if(path==='/api/donations') {
        strict(input,['provider','model','apiKey','mode','remainingUnits','maxCalls','expiresAt','consent','consentVersion']);
        if(!Object.hasOwn(models,input.provider)||input.model!==models[input.provider])throw error('invalid_model');
        if(input.mode!=='prepaid_remaining'||input.consent!==true||input.consentVersion!==DONOR_CONSENT_VERSION)throw error('consent_required');
        if(r.donations>=5)throw error('donation_rate_limit');
        if(credentials[input.provider]&&equal(input.apiKey,credentials[input.provider]))throw error('owner_key_already_configured');
        const donated=pool.addDonation({provider:input.provider,key:input.apiKey,mode:input.mode,remainingUnits:input.remainingUnits,maxCalls:input.maxCalls,expiresAt:input.expiresAt,nonce:randomBytes(16).toString('hex'),consent:{version:DONOR_CONSENT_VERSION,publicVisitorUse:true,ownKey:true,providerBilling:true,noEditorialControl:true}});
        r.donations++;await save();return response(201,{donationId:randomUUID(),...donated});
      }
      if(path==='/api/donations/revoke'||path==='/api/donations/mine'||path==='/api/donations/status') {
        strict(input,['revocationToken','revokeToken','donationId']);const token=input.revocationToken || input.revokeToken;
        const out=path.endsWith('/revoke')?pool.revoke(token):pool.status(token);await save();return response(200,out);
      }
      if(DONOR_PATHS.has(path))return response(405,{error:'method_not_allowed'});
      if(!['/api/session','/api/campaign/session'].includes(path)) {const session=app.sessions.get(input.sessionId);if(session&&session.ownerVisitor!==visitor)return response(403,{error:'session_not_owned'});}
      const meteredPath=['/api/respond','/api/campaign/respond','/api/speak'].includes(path);
      const audioKey=path==='/api/speak'?voiceAction(input):null;
      const legacyRequestId=createHash('sha256').update(visitor+'|'+path+'|'+(h['x-request-id'] || '')+'|'+body).digest('hex');
      const requestId=audioKey || legacyRequestId;
      pruneAudio();
      if(audioKey && ledger.audioCache[audioKey]) {const entry=ledger.audioCache[audioKey];entry.lastUsedAt=clock();await save();return entry.result;}
      for(const [id,record] of Object.entries(ledger.requests))if(clock()-record.createdAt>=20*60000)delete ledger.requests[id];
      const previous=ledger.requests[requestId] || (audioKey?ledger.requests[legacyRequestId]:null);
      if(meteredPath && previous) return previous.result || response(409,{error:'request_already_reserved'});
      if(meteredPath) {if(Object.keys(ledger.requests).length>=1000)throw error('request_storage_full');ledger.requests[requestId]={createdAt:clock(),status:'reserved'};await save();}
      const result=await gameRequest(method,path,body);
      if(audioKey&&result.isBase64Encoded)storeAudio(audioKey,result);
      if(meteredPath)ledger.requests[requestId]={createdAt:clock(),status:'completed',...(result.isBase64Encoded?{audioKey}:{result})};
      if(result.status===201&&['/api/session','/api/campaign/session'].includes(path)) {const sessionId=JSON.parse(result.body).sessionId;const session=app.sessions.get(sessionId);if(session)session.ownerVisitor=visitor;}
      await save();return result;
    }catch(e) {
      const safe=new Set(['invalid_schema','invalid_model','consent_required','invalid_key','invalid_donor_caps','invalid_expiry','invalid_revocation_token','key_already_donated','owner_key_already_configured','donation_rate_limit','donor_storage_full']);
      return response(safe.has(e.code)?400:e.code==='visitor_budget_exhausted'?429:503,{error:safe.has(e.code)?e.code:'gateway_unavailable'});
    }finally{visitor=null;busy=false;}
  }
  async function updateOwnerBalance({provider,remainingUnits,allowManual=false,manualFunded=false,asOf=null}) {
    if(!Object.hasOwn(models,provider)||(provider==='elevenlabs'&&!finite(remainingUnits))||(provider==='deepseek'&&manualFunded&&(!Number.isFinite(Date.parse(asOf))||Date.parse(asOf)>clock())))throw error('invalid_owner_report');ledger.owner[provider]={remainingUnits:finite(remainingUnits)?remainingUnits:0,manual:allowManual===true,manualFunded:manualFunded===true,asOf,mode:provider==='deepseek'?'provider_prepaid':'provider_characters',usedUnits:0,reservedCalls:0,balanceInitialized:finite(remainingUnits),status:'active',checkedAt:0,checkedAvailable:false};await save();return {updated:true,provider,remainingUnits};
  }
  return {handle,pool,app,save,state:ledger,updateOwnerBalance,close(){pool.close();}};
}
